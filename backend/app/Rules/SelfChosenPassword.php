<?php

namespace App\Rules;

use Closure;
use Illuminate\Contracts\Validation\ValidationRule;

/**
 * Требования к паролю, который человек задаёт себе сам. Решение владельца от 11.08.2026:
 * не короче шести символов, латиница, есть заглавная буква.
 *
 * Правило одно на весь портал — и для «Моей учётной записи», и для пароля, который
 * администратор задаёт вручную в карточке пользователя. Два набора требований разошлись
 * бы: в одном месте пароль приняли бы, в другом тот же самый отклонили.
 *
 * Выдаваемые порталом пароли под это правило **не подпадают** и остаются пятизначными
 * числовыми — так решил владелец. Смысл в том, что выданный пароль временный: после
 * входа портал предлагает завести свой, и вот он уже проверяется здесь.
 *
 * Про латиницу это не вкусовщина. Пароль с русскими буквами набирается только при русской
 * раскладке: человек, сменивший её или пришедший с телефона, не сможет войти и не поймёт
 * почему — поле показывает точки, а раскладку оно не показывает.
 */
class SelfChosenPassword implements ValidationRule
{
    public const MIN_LENGTH = 6;

    public function validate(string $attribute, mixed $value, Closure $fail): void
    {
        $password = (string) $value;

        if (mb_strlen($password) < self::MIN_LENGTH) {
            $fail('Пароль должен быть не короче '.self::MIN_LENGTH.' символов.');

            return;
        }

        // Печатные знаки ASCII: латинские буквы, цифры и обычная пунктуация. Отсекается
        // кириллица и невидимые символы, которые попадают при копировании из документа.
        if (preg_match('/^[\x21-\x7E]+$/', $password) !== 1) {
            $fail('Пароль записывается латиницей, без пробелов: русские буквы в нём набрать не получится.');

            return;
        }

        if (preg_match('/[A-Z]/', $password) !== 1) {
            $fail('В пароле должна быть хотя бы одна заглавная латинская буква.');
        }
    }
}
