<?php

namespace App\Support\Packages;

use Illuminate\Validation\ValidationException;

/**
 * Пакет выгружают файлом только после проверки.
 *
 * Разбор выгрузок 24.08.2026 нашёл образец, повторённый дважды: у ФИС и у ФРДО
 * отметка «выгружено» требовала пройденной проверки и говорила «выгрузка
 * заблокирована», а соседняя кнопка «скачать файлом» не проверяла ничего и
 * отдавала пакет с невалидными записями. **Защита стояла на учётной отметке, а
 * не на самой выгрузке**: человек, которому портал только что отказал, нажимал
 * соседнюю кнопку и получал тот же пакет целиком — а в системе оставалось «не
 * выгружено», то есть след события терялся вместе с запретом.
 *
 * Условие отметки сюда скопировать нельзя, и это главное в этом классе.
 * `markExported` пропускает **только** `ready`; для файла это было бы неверно —
 * уже выгруженный пакет скачивают повторно (файл потеряли, отправили не тому,
 * нужен второй экземпляр), и запрещать это значит мешать работе там, где вреда
 * нет. Запрещается ровно то, что вредно: пакет, который **не проверяли** или
 * который проверку **провалил**.
 */
final class PackageExport
{
    /** Пакет собран, но проверку ещё не запускали. */
    private const NOT_CHECKED = 'draft';

    /** Проверка прошла и нашла ошибки в записях. */
    private const FAILED = 'validation_failed';

    /**
     * @param  string  $status  состояние пакета
     * @param  string  $system  куда выгружают: «ФИС ГИА» или «ФРДО»
     *
     * @throws ValidationException если пакет выгружать нельзя
     */
    public static function assertExportable(?string $status, string $system): void
    {
        if ($status === self::NOT_CHECKED) {
            throw ValidationException::withMessages([
                'status' => "Пакет ещё не проверялся, выгружать его в {$system} рано. ".
                    'Нажмите «Проверить»: если ошибок не найдётся, выгрузка откроется.',
            ]);
        }

        if ($status === self::FAILED) {
            throw ValidationException::withMessages([
                'status' => "Пакет не прошёл проверку, и выгрузка в {$system} заблокирована до устранения ошибок. ".
                    'Записи с ошибками видно в самом пакете — исправьте их и проверьте пакет заново.',
            ]);
        }
    }
}
