<?php

namespace App\Support\Auth;

use Illuminate\Support\Carbon;

/**
 * Временный пароль, который портал выдаёт вместо забытого или при заведении
 * учётной записи.
 *
 * До 23.08.2026 это были пять цифр — 90 000 вариантов. Ограничитель даёт пять
 * попыток в минуту на учётную запись, то есть перебор занимал около недели
 * непрерывной работы на одну запись. Само по себе это терпимо ровно до тех пор,
 * пока пароль временный; но «до первого входа» у записи, которой никто не
 * пользовался, не наступает никогда, и временное становилось постоянным. А
 * учётные записи заводятся пачкой на весь контингент.
 */
class TemporaryPassword
{
    /**
     * Восемь знаков без похожих друг на друга.
     *
     * Ни нуля с «O», ни единицы с «l» и «I»: пароль диктуют вслух и вводят с
     * листка, и спутанный знак стоит звонка. Оставшихся 30 знаков хватает: 30
     * в восьмой — это шестьсот миллиардов вариантов против прежних девяноста
     * тысяч, и перебор перестаёт иметь смысл.
     */
    private const ALPHABET = 'abcdefghjkmnpqrstuvwxyz23456789';

    private const LENGTH = 8;

    /**
     * Сколько живёт выданный пароль.
     *
     * Тридцать дней — это про запас: учётные записи раздают в начале года, и
     * люди приходят за ними неделями. Дальше пароль перестаёт работать, и
     * нужен новый — неиспользованная запись не остаётся с выданным паролем
     * навсегда.
     */
    public const TERM_DAYS = 30;

    public static function generate(): string
    {
        $alphabet = self::ALPHABET;
        $last = strlen($alphabet) - 1;
        $password = '';

        for ($i = 0; $i < self::LENGTH; $i++) {
            $password .= $alphabet[random_int(0, $last)];
        }

        return $password;
    }

    /** До какого момента годен выданный сейчас пароль. */
    public static function expiresAt(): Carbon
    {
        return now()->addDays(self::TERM_DAYS);
    }
}
