<?php

namespace App\Support\Auth\Providers;

/**
 * Контракт внешнего способа входа: Telegram, MAX и что появится дальше.
 *
 * Провайдер отвечает ровно на один вопрос: **этот ответ действительно от провайдера
 * и о ком он**. Пускать или не пускать решает портал, и решает одинаково для всех
 * провайдеров — иначе каждый следующий вход принесёт свою логику доступа.
 *
 * Проверка подписи выполняется **только на сервере** и только по секрету, который
 * во frontend не попадает. У Telegram это HMAC-SHA256 по строке проверки данных
 * ключом из токена бота плюс контроль давности `auth_date`.
 */
interface ExternalIdentityProvider
{
    /** Короткий код, он же значение колонки `provider`. */
    public function code(): string;

    /** Как назвать способ входа человеку. */
    public function name(): string;

    /**
     * Проверить ответ провайдера и сказать, о ком он.
     *
     * @param array<string, mixed> $payload то, что прислал виджет или callback
     * @return ExternalIdentity|null null — подпись не сошлась или ответ просрочен.
     *                               Причину наружу не раскрываем: это подсказка подбирающему.
     */
    public function verify(array $payload): ?ExternalIdentity;
}
