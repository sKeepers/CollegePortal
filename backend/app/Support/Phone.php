<?php

namespace App\Support;

/**
 * Единое написание телефона для выгрузок: `+7 962 448 7133`.
 *
 * Владелец сверял выгрузку с тем, что вводил, и видел расхождение: одни номера
 * приходили с плюсом, другие без. Замер на стенде 11.08.2026 показал, откуда
 * это: из 676 номеров 671 лежит с плюсом и 5 без. Теряется плюс не на
 * выгрузке — её дело показать, что лежит, — а на **загрузке**: общие данные
 * человека пишет только `PersonService`, и он оставляет от номера одни цифры.
 * Поэтому вид номера в файле зависел от того, правили ли когда-нибудь карточку
 * через портал, и один и тот же реестр показывал два написания сразу.
 *
 * Здесь выгрузка приводится к тому же виду, который портал показывает на
 * экране (`frontend/src/utils/phone.js`): человек сверяет файл с тем, что видит,
 * а не с тем, как оно лежит в базе.
 *
 * Хранение не меняется. Обратная загрузка снимет пробелы и плюс так же, как
 * снимала их раньше, поэтому круг устойчив: вторая выгрузка того же реестра
 * даёт тот же файл до символа.
 *
 * Чужие написания не трогаются: короткий внутренний номер, международный или
 * заведомо неполный остаются как есть — правка вслепую исказила бы данные.
 */
final class Phone
{
    public static function forExport(?string $value): ?string
    {
        $raw = trim((string) $value);

        if ($raw === '') {
            return $value === null ? null : '';
        }

        $digits = preg_replace('/\D+/', '', $raw) ?? '';

        // Одиннадцать цифр с 7 или 8 впереди — российский номер. Десять цифр
        // считаются российскими только начиная с девятки: правило «любые десять
        // цифр — это Россия» ловило и чужие номера, немецкий `+49 30 123456`
        // превращался в `+7 493 012 3456`. Тест на этом и поймал.
        if (preg_match('/^(?:7|8)(\d{3})(\d{3})(\d{2})(\d{2})$/', $digits, $matches)
            || preg_match('/^(9\d{2})(\d{3})(\d{2})(\d{2})$/', $digits, $matches)) {
            return "+7 {$matches[1]} {$matches[2]} {$matches[3]}{$matches[4]}";
        }

        return $raw;
    }
}
