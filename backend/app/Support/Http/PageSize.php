<?php

namespace App\Support\Http;

use Illuminate\Http\Request;

/**
 * Сколько строк отдавать в одном ответе списка.
 *
 * До 28.08.2026 каждый список выбирал сам и выбирал числом: `paginate(20)` у
 * студентов, `paginate(30)` у людей, `paginate(50)` у пропусков. Запрос при
 * этом **не спрашивали вовсе**, и `per_page` был декорацией: замерено на
 * стенде — `students?per_page=1000` отдавал 20 строк из 596, `subjects` 20 из
 * 140, `people` 30 из 841.
 *
 * Дороже всего обошлось не само усечение, а его невидимость. Экран «Студенты»
 * показывал двадцать строк и рядом подпись «Найдено записей: 596»: `data` брали
 * из ответа, `meta` выбрасывали, и **страница со списком в коде были
 * неразличимы**. Хранилища, честно пославшие `per_page`, получали то же
 * усечение и выглядели правильными: `semesterGrades.js` просил 500 дисциплин и
 * получал 20 из 140.
 *
 * Отсюда правило: **список обязан слушать, сколько у него просят**, а потолок
 * ставится один на всех и здесь.
 *
 * Потолок — утверждение не о колледже, а об одном ответе: сколько строк
 * разумно собрать, отдать и разобрать за раз. Поэтому он не устареет от роста
 * контингента: вырастет число страниц, а не размер ответа. Тот, кому нужен
 * список целиком, дочитывает страницы — на фронтенде это делает `api.listAll`.
 */
class PageSize
{
    /**
     * Больше пятисот строк в одном ответе не отдаётся никому.
     *
     * На 28.08.2026 самый длинный список портала — 843 цифровых пропуска, за
     * ним 841 человек и 596 студентов. При этом потолке они приходят двумя
     * ответами, всё остальное — одним.
     */
    public const MAX = 500;

    public static function from(Request $request, int $default): int
    {
        $asked = $request->integer('per_page');

        if ($asked < 1) {
            return $default;
        }

        return min($asked, self::MAX);
    }
}
