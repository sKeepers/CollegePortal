<?php

namespace App\Support\Notifications;

/**
 * Канал доставки уведомления: MAX сегодня, Telegram и почта — если появятся.
 *
 * Контракт нарочно узкий: канал знает, как называется и как отправить текст по адресу
 * диалога. Кому и по какому поводу писать — не его дело; иначе каждый следующий канал
 * принесёт свою логику подписок, и они разойдутся.
 *
 * **Telegram не сделан не потому, что забыт.** Замер 11.08.2026: из трёх адресов службы
 * с боевого сервера отвечает один, DNS отдаёт их по кругу, режет вышестоящий провайдер.
 * Отправка работала бы через раз. Канал остаётся абстракцией ровно для того, чтобы
 * телеграмная реализация встала сюда без переписывания, когда появится чистый выход.
 */
interface NotificationChannel
{
    /** Короткий код, он же значение колонки `channel`. */
    public function code(): string;

    /** Как назвать канал человеку. */
    public function name(): string;

    /**
     * Отправить текст в диалог.
     *
     * @param string $chatId идентификатор диалога, полученный после того, как человек
     *                       нажал «Старт»: **бот не может написать первым**
     * @return bool доставлено ли. Причину наружу не отдаём: журнал отправок пишет
     *              вызывающий, и ему нужен исход, а не текст ошибки провайдера.
     */
    public function send(string $chatId, string $text): bool;
}
