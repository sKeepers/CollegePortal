<?php

namespace App\Support\Notifications;

use App\Models\User;

/**
 * Умеет собрать своё уведомление заново.
 *
 * Нужно повтору доставки. **Текста в журнале доставок нет намеренно:** в сообщении лежат
 * оценки, пропуски и расписание конкретного человека, и второй копии этих данных в базе
 * быть не должно. Поэтому повторяется не текст, а факт — а собрать факт в текст умеет
 * только тот, кто умеет его собирать, то есть сама рассылка.
 *
 * Второе назначение важнее первого: **сборка заново отвечает и на вопрос, жива ли ещё
 * новость.** Журнал закрыли, занятие отменили, день прошёл — повторять нечего, и
 * `null` здесь значит «прекратить попытки», а не «ошибка».
 */
interface RebuildsNotification
{
    /**
     * @param string $dedupeKey ключ повтора: событие и то, что его уточняет, — дата или окно
     * @return string|null null — новость больше неактуальна, повторять нечего
     */
    public function rebuild(User $user, string $dedupeKey): ?string;
}
