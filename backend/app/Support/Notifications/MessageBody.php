<?php

namespace App\Support\Notifications;

use Illuminate\Support\Collection;

/**
 * Тело сообщения-списка: заголовок и перечень, ограниченный по длине.
 *
 * Свёртка по числу сообщений в рассылках есть — все они шлют одно сообщение на
 * человека. А вот длина самого сообщения не ограничивалась ничем: список рос
 * строкой на занятие. Замер на стенде 24.08.2026: шестьдесят изменённых занятий
 * дают 2662 знака, то есть предел мессенджера (около 4000) переступается уже
 * примерно на девяноста. Это не выдуманный случай: перенос занятий одного
 * преподавателя в другую аудиторию на семестр — как раз сотня строк.
 *
 * Что важно: слишком длинное сообщение не приходит **обрезанным**, оно не
 * приходит вовсе. Отправка возвращает отказ, доставка записывается неудачной, и
 * человек не получает ничего, а учебная часть об этом не узнаёт. Тихая пропажа
 * хуже длинного письма, поэтому список подрезается здесь.
 */
final class MessageBody
{
    /** Сколько строк показывать, прежде чем свернуть остаток в «и ещё N». */
    public const MAX_LINES = 10;

    /**
     * @param  iterable<int, string>  $lines
     */
    public static function list(string $title, iterable $lines, int $limit = self::MAX_LINES): string
    {
        $all = Collection::make($lines)->filter(fn (string $line): bool => trim($line) !== '')->values();

        if ($all->count() <= $limit) {
            return $all->isEmpty() ? $title : $title."\n".$all->implode("\n");
        }

        $shown = $all->take($limit);
        $rest = $all->count() - $limit;

        return $title."\n".$shown->implode("\n")."\n…и ещё ".$rest;
    }
}
