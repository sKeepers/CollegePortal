<?php

namespace App\Support\People;

/**
 * Телефон, лежащий внутри строки адреса.
 *
 * Контингент завели 22.08.2026 из документа учебной части, где адрес и телефон
 * стоят в одной ячейке. Разбор при загрузке разделил их не везде: **в 406
 * строках из 593 телефон приехал внутри адреса**, а собственная графа телефона
 * осталась пустой. Телефон в портале есть, а найти его нельзя — ни поиском, ни
 * выгрузкой, ни рассылкой.
 *
 * Чистка 22.08 сняла 175 таких строк и остановилась, потому что искала слово
 * «тел» перед цифрами. Остальные 231 написаны без него — «…, кв. 12,
 * 89XXXXXXXXX», — и правило их просто не видело. **Это не возврат прежней
 * ошибки: они лежат нетронутыми с самой загрузки.** Выгрузки ФИС здесь ни при
 * чём: во всех четырёх файлах телефона нет ни в одной из 24 колонок, проверено
 * построчно 24.08.
 *
 * Правило намеренно узкое, потому что адрес пострадать не должен:
 *
 * - телефоном считается только мобильный российский номер — необязательные `8`,
 *   `7` или `+7`, затем `9XX` и ещё семь цифр. Индекс, номер дома и квартиры под
 *   это не подходят;
 * - номеров в строке больше одного — не трогаем, разбирает человек;
 * - после номера идёт ещё текст (приказ о переводе, название школы, страна) —
 *   не трогаем: вырезать из середины опаснее, чем оставить;
 * - адрес после подреза короче десяти знаков — не трогаем, это огрызок;
 * - цифровой хвост, не похожий на телефон, — в отчёт. Так нашлась строка с
 *   одиннадцатью цифрами, начинающимися с `99`: опечатка, а не номер.
 *
 * «Улица Тельмана» в карточках есть, и слово «тел» из неё не вырезается: маркер
 * снимается только с конца уже отрезанного адреса и только целым словом.
 */
final class AddressPhone
{
    /**
     * Российский мобильный: необязательный код страны, затем `9XX` и семь цифр.
     * Разделителями считаются пробел, дефис и скобки — то, чем номер разбивают
     * на группы. Запятая в разделители не входит: «д. 8, 9-й проезд» номером не
     * станет.
     */
    private const TOKEN = '/(?<![0-9])(?:\+7|[78])?[\s(-]*9\d{2}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?![0-9])/u';

    /**
     * «тел», «тел.», «телефон», «т.» на самом конце отрезанного адреса.
     *
     * Перед маркером не должно стоять ни буквы, ни цифры. Без этого `т` съело бы
     * последнюю букву слова — «ул. Университет» стала бы «ул. Университе», а
     * «Котел» — «Ко», — и отрезало бы литеру дома в «д. 5т».
     *
     * Маркер снимается **до** подрезки хвостовых запятых и точек: если сначала
     * убрать точку, «т.» превратится в «т», и одинокая буква останется в адресе.
     * Ровно это и вышло на пробе десяти карточек 24.08.2026.
     */
    private const MARKER_TAIL = '/(?<![\p{L}0-9])(?:тел(?:ефон)?|т)[\s.:№-]*$/iu';

    /** Чем адрес заканчиваться не должен: остатки запятых и точек после подреза. */
    private const EDGE = " \t\r\n,;.:/-";

    /**
     * Цифровой хвост короче семи цифр не подозрителен: шесть — это почтовый
     * индекс, меньше — номер дома или квартиры.
     */
    private const SUSPICIOUS_TAIL_DIGITS = 7;

    /** Причины, по которым строка уходит человеку, человеческими словами. */
    public const PROBLEMS = [
        'several_phones' => 'в строке больше одного номера',
        'text_after_phone' => 'после номера идёт ещё текст',
        'address_too_short' => 'после подреза от адреса ничего не осталось',
        'digits_not_a_phone' => 'цифровой хвост на телефон не похож',
    ];

    /**
     * Разобрать строку адреса.
     *
     * `null` — телефона в строке нет и делать нечего.
     */
    public static function split(?string $address): ?AddressPhoneSplit
    {
        $value = trim((string) $address);

        if ($value === '') {
            return null;
        }

        // Строка без единой буквы — это не адрес. У таких карточек адреса не
        // записали вовсе, а номер положили в ближайшую графу.
        if (! preg_match('/\p{L}/u', $value)) {
            $phone = self::eleven(self::digits($value));

            return $phone === null ? null : new AddressPhoneSplit('', $phone);
        }

        if (! preg_match_all(self::TOKEN, $value, $matches, PREG_OFFSET_CAPTURE)) {
            return self::hasSuspiciousTail($value)
                ? new AddressPhoneSplit($value, '', 'digits_not_a_phone')
                : null;
        }

        if (count($matches[0]) > 1) {
            return new AddressPhoneSplit($value, '', 'several_phones');
        }

        [$token, $offset] = $matches[0][0];

        $phone = self::eleven(self::digits($token));

        if ($phone === null) {
            return new AddressPhoneSplit($value, '', 'digits_not_a_phone');
        }

        // Смещение из PREG_OFFSET_CAPTURE считается в байтах, поэтому и режем
        // байтовым substr: смешивать его с mb_substr нельзя.
        $tail = trim(substr($value, $offset + strlen($token)), self::EDGE);

        if ($tail !== '') {
            return new AddressPhoneSplit($value, '', 'text_after_phone');
        }

        $head = (string) preg_replace(self::MARKER_TAIL, '', substr($value, 0, $offset));
        $head = rtrim($head, self::EDGE);

        if (mb_strlen($head) < 10) {
            return new AddressPhoneSplit($value, '', 'address_too_short');
        }

        return new AddressPhoneSplit($head, $phone);
    }

    /** Одиннадцать цифр или ничего: десятизначный номер дописывается восьмёркой. */
    private static function eleven(string $digits): ?string
    {
        if (strlen($digits) === 10) {
            $digits = '8'.$digits;
        }

        return strlen($digits) === 11 ? $digits : null;
    }

    private static function hasSuspiciousTail(string $value): bool
    {
        // Якорь на конец строки обязателен: без него совпадением стал бы первый
        // же номер дома, а не хвост.
        if (! preg_match('/[0-9][0-9\s()+-]*$/u', $value, $match)) {
            return false;
        }

        return strlen(self::digits($match[0])) >= self::SUSPICIOUS_TAIL_DIGITS;
    }

    private static function digits(?string $value): string
    {
        return preg_replace('/\D+/', '', (string) $value) ?? '';
    }
}
