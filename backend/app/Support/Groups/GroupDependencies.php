<?php

namespace App\Support\Groups;

use Illuminate\Support\Facades\DB;

/**
 * Что ссылается на учебную группу.
 *
 * Нужно перед удалением группы. На `groups` семь внешних ключей с
 * `ON DELETE CASCADE` — студенты, экзамены, занятия журнала, расписание в двух
 * таблицах, шаблоны расписания и позиции нагрузки — и три с `SET NULL`. Удалить
 * группу, на которую ещё кто-то ссылается, значит молча снести половину
 * учебного года: база сделает это без единого предупреждения.
 *
 * **Итоговые оценки за семестр стоят здесь не ради каскада, а ради отказа, и разница
 * между двумя правилами удаления тут решающая.** Каскад уносит строку целиком — потеря
 * заметна сразу, её видно по пустому списку. `SET NULL` **оставляет строку и стирает
 * смысл**: ведомость никуда не денется, а группа, в которой оценку ставили, исчезнет,
 * и со стороны всё будет выглядеть исправным.
 *
 * Из этих оценок собирается приложение к диплому. Значит удаление группы молча
 * испортило бы документ, который человек получает на всю жизнь, а заметили бы это на
 * выпуске — в 2027 году, когда восстанавливать будет не из чего. Поэтому портал обязан
 * отказать в удалении и назвать причину, а не занулить колонку.
 *
 * Поэтому «группа пустая» проверяется **запросом**, а не выводится из того, что
 * студентов только что перенесли.
 *
 * Список закреплён тестом `MergeGroupsByFundingLetterTest`, метод
 * `test_the_list_of_dependants_matches_the_schema`: он читает внешние ключи
 * **из самой схемы** и падает, если появился ключ, которого здесь нет, или если
 * ссылка сменила правило удаления. Без этого перечень однажды разойдётся со
 * схемой и не скажет об этом.
 *
 * (Здесь стояло имя `GroupDependenciesAreKnownTest` — такого класса нет и не
 * было: проверка живёт вместе с тестом слияния групп, ради которого её и
 * писали. Ссылка на несуществующий тест хуже, чем её отсутствие: она обещает
 * защиту, которую читатель не станет искать.)
 */
final class GroupDependencies
{
    /**
     * Таблица → колонка со ссылкой на группу.
     *
     * Перечень однороден, а правила удаления у ссылок **разные**, и читающий
     * глазами решит, что везде каскад. Что не каскад — в `NULLIFIED` ниже.
     *
     * @var array<string, string>
     */
    public const TABLES = [
        'students' => 'group_id',
        'exams' => 'group_id',
        'journal_lessons' => 'group_id',
        'schedule_entries' => 'group_id',
        'schedule_lessons' => 'group_id',
        'schedule_templates' => 'group_id',
        'teaching_load_items' => 'group_id',
        'graduates' => 'group_id',
        'teaching_loads' => 'group_id',
        'semester_grades' => 'group_id',
    ];

    /**
     * Ссылки, которые при удалении группы **обнуляются**, а не уносят строку.
     *
     * Отказ в удалении одинаков для всех — поведение это не меняет. Меняет оно
     * то, что видит человек: в однородном перечне `SET NULL` выглядит мягким
     * случаем, а он строже. Каскад уносит строку, и потеря заметна: список
     * опустел. `SET NULL` оставляет строку и стирает смысл — ведомость с
     * оценками на месте, а группы, в которой их ставили, нет, и со стороны всё
     * исправно. Проверить нечем: ни отсутствующей строки, ни ошибки.
     *
     * Поэтому в сообщении об отказе они помечаются отдельно: тому, кто читает
     * отказ, важно знать, что за этими таблицами не «лишние данные», а данные,
     * потерю которых он не увидит.
     *
     * Список закреплён тем же тестом, что и `TABLES`: он читает правило
     * удаления из схемы, и ссылка, сменившая правило, роняет прогон.
     *
     * @var list<string>
     */
    public const NULLIFIED = ['graduates', 'teaching_loads', 'semester_grades'];

    /**
     * Что осталось висеть на группе.
     *
     * @return array<string, int> таблица → сколько строк; пустой массив, если ничего
     */
    public static function leftovers(int $groupId): array
    {
        $left = [];

        foreach (self::TABLES as $table => $column) {
            $count = DB::table($table)->where($column, $groupId)->count();

            if ($count > 0) {
                $left[$table] = $count;
            }
        }

        return $left;
    }

    /**
     * Человеческое перечисление для сообщения об отказе.
     *
     * Таблицы с обнуляемой ссылкой помечаются: их потеря не видна снаружи, и
     * человек, читающий отказ, должен понимать, что рискует не строками, а
     * смыслом уцелевших строк.
     */
    public static function describe(array $leftovers): string
    {
        return implode(', ', array_map(
            fn (string $table, int $count): string => sprintf(
                '%s (%d%s)',
                $table,
                $count,
                in_array($table, self::NULLIFIED, true) ? ', ссылка обнулилась бы молча' : '',
            ),
            array_keys($leftovers),
            array_values($leftovers),
        ));
    }
}
