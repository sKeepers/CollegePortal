<?php

namespace App\Support\Rfid;

use Illuminate\Validation\ValidationException;

/**
 * Приведение номера RFID-карты к общему виду.
 *
 * Одна и та же карта EM-Marine читается по-разному в зависимости от настройки
 * считывателя: десять десятичных цифр, восемь или десять шестнадцатеричных,
 * либо «3+5» вида `0009,12345`. Пока в системе один формат, всё сходится; стоит
 * подключить второй считыватель с другой настройкой — и привязанная карта
 * перестаёт открывать дверь, а выглядит это как неисправность.
 *
 * Общий вид у нас — **десять десятичных цифр**: так номера записаны в
 * действующей СКУД на проходной, и на этот формат настраивается парк
 * считывателей.
 *
 * Формат «3+5» сюда не приводится намеренно. Он несёт только 24 бита из 32, и
 * восстановить из него полный номер нельзя: дополнение нулями дало бы **чужую**
 * карту, причём молча. Поэтому такой ввод отклоняется с объяснением, что
 * переключить в считывателе.
 */
final class CardNumber
{
    /** Длина общего вида: десять десятичных цифр. */
    public const LENGTH = 10;

    public static function normalize(string $value): string
    {
        $raw = trim($value, " \t\r\n\0");

        if ($raw === '') {
            throw ValidationException::withMessages([
                'uid' => 'Номер карты пуст. Поднесите карту к считывателю ещё раз.',
            ]);
        }

        if (str_contains($raw, ',')) {
            throw ValidationException::withMessages([
                'uid' => 'Считыватель отдаёт номер в формате «3+5» — он короче настоящего, и по нему карты можно перепутать. Переключите считыватель на десятичный формат из 10 цифр.',
            ]);
        }

        // Разделители внутри номера считыватели ставят по-разному; на сам номер
        // они не влияют.
        $compact = preg_replace('/[\s\-]+/', '', $raw) ?? $raw;

        if (preg_match('/^\d+$/', $compact) === 1) {
            $digits = ltrim($compact, '0');
            $digits = $digits === '' ? '0' : $digits;

            // Длиннее общего вида не укорачиваем: обрезка старших разрядов —
            // это ровно тот способ перепутать две карты, от которого мы бежим.
            return strlen($digits) >= self::LENGTH
                ? $digits
                : str_pad($digits, self::LENGTH, '0', STR_PAD_LEFT);
        }

        if (preg_match('/^[0-9A-Fa-f]+$/', $compact) === 1) {
            return strtoupper($compact);
        }

        throw ValidationException::withMessages([
            'uid' => 'Номер карты должен состоять из цифр. Проверьте раскладку клавиатуры и настройку считывателя.',
        ]);
    }
}
