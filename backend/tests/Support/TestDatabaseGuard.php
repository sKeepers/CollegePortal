<?php

namespace Tests\Support;

use RuntimeException;

/**
 * Отказ от прогона, направленного на живую базу.
 *
 * `phpunit.pgsql.xml` намеренно не задаёт `DB_DATABASE`: четыре области гоняют
 * прогоны одновременно, и общее имя они затирали бы друг у друга. Значит имя
 * приходит из `.env` worktree — а туда его ставят руками, ради замера на живых
 * данных, и возвращают не всегда. `RefreshDatabase` начинает с пересоздания
 * схемы, поэтому один такой прогон стирает стенд целиком: людей, группы,
 * пропуска, проходы, бланки.
 *
 * Замер 24.08.2026: из 27 файлов `.env` на стенде 12 смотрели прямо на рабочую
 * базу, один не задавал имя вовсе. Это не случайность одного чата, это
 * устройство, и внимательность его не лечит.
 *
 * **Проверка белым списком, а не чёрным.** Раньше здесь стоял перечень из
 * одного имени `college_portal`; он не ловил ни опечатку, ни базу соседа, ни
 * боевую базу, которая называется иначе. Теперь наоборот: прогон идёт только на
 * базу, чьё имя **само себя объявляет тестовым** — содержит `test`. Всё
 * остальное считается живым, пока не доказано обратное; ошибиться в эту сторону
 * стоит одного понятного отказа, а в другую — стенда.
 *
 * **Второе правило — про соседей, а не про боевую базу.** Четыре области гоняют
 * прогоны одновременно, и если две возьмут одно тестовое имя, они вытрут прогон
 * друг другу: `RefreshDatabase` пересоздаёт схему под ногами у второго. Сегодня
 * имена разводили руками, помня об этом; правило избавляет от «помнить». Имя
 * обязано называть ваш worktree — кроме общей `college_portal_test`, на которой
 * идёт обычный прогон и которая имени worktree не содержит законно.
 *
 * Имя worktree приходит переменной `CP_WORKTREE`: внутри контейнера его иначе
 * не узнать — монтируется только `backend`, и каталог виден как
 * `/var/www/html`. Рецепт запуска её передаёт. Если переменной нет, остаётся
 * первое правило: сторож не молчит, но и не требует того, чего не может
 * проверить.
 */
final class TestDatabaseGuard
{
    /**
     * Пометка «прогон здесь не настроен», которую области ставят в `.env`
     * вместо имени базы. Она намеренно указывает в никуда, и человеку надо
     * сказать именно это, а не «имя не содержит test»: он ничего не ломал,
     * он ещё не выбрал имя.
     */
    private const NOT_CONFIGURED_MARKER = 'NO_SUCH_DB';

    /**
     * @throws RuntimeException если прогон направлен не на тестовую базу
     */
    public static function assertSafe(?string $driver, mixed $database): void
    {
        // Прогон по умолчанию идёт в памяти и до сервера баз не доходит вовсе.
        if ($driver === 'sqlite') {
            return;
        }

        if (! is_string($database) || trim($database) === '') {
            throw new RuntimeException(self::message(
                'Имя базы для прогона не задано.',
                'Пустое значение в `.env` — это пустая строка, а не «как по умолчанию»: '.
                'подключение уйдёт в базу с именем пользователя, и на что оно попадёт, заранее не известно.'
            ));
        }

        if (str_contains($database, self::NOT_CONFIGURED_MARKER)) {
            throw new RuntimeException(self::message(
                "В `.env` этого worktree стоит заглушка «{$database}» — прогон здесь ещё не настроен.",
                'Заглушку ставят намеренно, чтобы прогон не ушёл в чужую базу, пока имя не выбрано. '.
                'Ничего не сломано: осталось вписать своё имя.'
            ));
        }

        if (! str_contains(mb_strtolower($database), 'test')) {
            throw new RuntimeException(self::message(
                "Прогон направлен на базу «{$database}», а она не объявлена тестовой.",
                'Тесты пересоздают схему: `RefreshDatabase` стёр бы эту базу целиком, вместе с данными.'
            ));
        }

        self::assertNamesTheWorktree($database);
    }

    /**
     * Общая тестовая база, на которой идёт обычный прогон. Имени worktree она не
     * содержит законно, и требовать его от неё нельзя: сторож, мешающий в самом
     * частом случае, будет отключён, а отключённый сторож хуже отсутствующего.
     */
    private const SHARED_TEST_DATABASE = 'college_portal_test';

    private static function assertNamesTheWorktree(string $database): void
    {
        $worktree = trim((string) (getenv('CP_WORKTREE') ?: ''));

        if ($worktree === '' || $database === self::SHARED_TEST_DATABASE) {
            return;
        }

        if (str_contains(mb_strtolower($database), mb_strtolower($worktree))) {
            return;
        }

        throw new RuntimeException(
            "Прогон в worktree «{$worktree}» направлен на базу «{$database}», а её имя не называет этот worktree. ".
            'Соседняя область может взять то же имя, и тогда `RefreshDatabase` пересоздаст схему под ногами у чужого прогона: '.
            'оба увидят падения, не связанные с их правками. '.
            "Назовите базу «college_portal_test_{$worktree}» — или используйте общую «".self::SHARED_TEST_DATABASE.'», если гоняете один.'
        );
    }

    private static function message(string $what, string $why): string
    {
        return $what.' '.$why.' '.
            'Поправьте `DB_DATABASE` в `backend/.env` своего worktree: имя обязано содержать `test` — '.
            'например, `college_portal_test_<метка вашей области>`. Свою базу заводят так: '.
            'docker exec college_dev_postgres psql -U college_user -d postgres -c "CREATE DATABASE college_portal_test_<метка>". '.
            'Проверка снимается только настоящим переименованием базы, и это намеренно: '.
            'отказ стоит одного понятного сообщения, а ошибка в другую сторону — всего стенда.';
    }
}
