<?php

namespace Tests\Feature;

use Tests\TestCase;

/**
 * Экраны прав, ролей, учётных записей и журнала не выдают отказ за пустоту.
 *
 * Замер 04.09.2026 17:20 UTC на стенде, обрыв одного запроса на экран: все
 * четыре при отказе говорили «Пользователи не найдены», «Роли не найдены»,
 * «Разрешения не найдены», «Событий аудита нет» — то есть **утверждали о правах
 * человека и о следе в журнале** ровно то, чего не спрашивали. Баннер ошибки
 * рядом стоял и не спасал: читают крупную подпись, а не мелкую полосу.
 *
 * Здесь это дороже, чем на других экранах. «Разрешения не найдены» читается как
 * «прав у роли нет», а «Событий аудита нет» — как «выгрузка следа не оставила»:
 * пункт 29 приёмки именно на этот экран и смотрит, и по такому ответу человек
 * пойдёт искать поломку в журнале сервера вместо обновления страницы.
 *
 * Проверка читает исходник, потому что поведение здесь не выдумать из ответов
 * API: подпись рисуется на стороне браузера, а фронтенд-тестов в портале нет
 * вовсе. Обратная сторона — обход с обрывом запроса (`asking-failed-access.mjs`
 * рядом с `look.js`); держать надо обе, они ловят разное.
 *
 * **Форму записи проверка не навязывает, и это не мелочь.** Отличить отказ можно
 * двумя способами, оба живут в портале: тернарник в одном `AppEmptyState`
 * (`:title="store.error ? … : …"`) и два соседних тега с `v-if="!store.error"` /
 * `v-else` — так написан реестр справок. Сторож, знающий одну форму, слеп ко
 * второй и вынуждает переписывать работающие экраны под себя; поэтому смотрим
 * **группу соседних пустых состояний** и требуем, чтобы отказ был спрошен
 * где-то в ней.
 */
class EmptyStateTellsFailureTest extends TestCase
{
    /**
     * Экран → подпись, которая врала при отказе; подписей может быть несколько.
     *
     * Список там, где их больше одной: у экрана карт подписи разные на разных
     * вкладках — «Карт нет» в реестре, «Записей нет» в журнале, — и одна
     * строка на файл оставила бы вторую вкладку без сторожа.
     *
     * @var array<string, string|list<string>>
     */
    private const SCREENS = [
        'pages/admin/users/UsersPage.vue' => 'Пользователи не найдены',
        'pages/admin/roles/RolesPage.vue' => 'Роли не найдены',
        'pages/admin/permissions/PermissionsPage.vue' => 'Разрешения не найдены',
        'pages/admin/audit/AuditPage.vue' => 'Событий аудита нет',

        // Область студентов и документов, замер 03-04.09.2026 тем же способом
        // (обрыв одного запроса на экран, `asking-failed-docs.mjs`). Три экрана
        // называли число, которого не считали: «Найдено записей: 0» при 618
        // студентах, «Найдено людей: 0» при 241, «Найдено выпускников: 0» при 9,
        // и каждый советовал менять фильтры или заводить запись. ФРДО и ФИС на
        // стенде пусты по-настоящему, поэтому врали не числом, а тем, что при
        // отказе и при пустоте говорили слово в слово одно и то же.
        'pages/students/StudentsPage.vue' => 'Студенты не найдены',
        'pages/people/PeoplePage.vue' => 'Люди не найдены',
        'pages/graduation/GraduationPage.vue' => 'Выпускники не найдены',
        'pages/frdo/FrdoPage.vue' => 'Пакеты ФРДО не найдены',
        'pages/fis/FisPage.vue' => 'Пакеты ФИС не найдены',
        // Учебный процесс, замер 03.09.2026 тем же обрывом: шесть экранов из
        // семи при отказе запроса утверждали о колледже то, чего не
        // спрашивали, и пять называли рядом число, которого не считали —
        // «Найдено нагрузок: 0», «Найдено экзаменов: 0», «Найдено учебных
        // планов: 0», «Занятий: 0; не заполнено: 0; ожидают подписи: 0».
        'pages/teaching-load/TeachingLoadPage.vue' => 'Нагрузка не найдена',
        'pages/exams/ExamsPage.vue' => 'Экзамены не найдены',
        'pages/curricula/CurriculaPage.vue' => 'Учебные планы не найдены',
        'pages/journal/JournalPage.vue' => 'Данные журнала не найдены',
        'pages/attendance/AttendancePage.vue' => 'Нет данных для анализа',
        'pages/journal/SemesterGradesPage.vue' => 'Выберите группу и дисциплину',

        // Проходная, карты и общежитие, замер 03.09.2026 тем же обрывом:
        // «Корпуса не заведены. Добавьте корпуса и точки прохода» стояло на
        // списке для эвакуации при трёх заведённых корпусах, «Выпустите первый
        // QR-пропуск» — при 861 живом пропуске, «Карт нет» — при 244 картах.
        'pages/access/MusterPage.vue' => 'Корпуса не заведены',
        'pages/access/AccessReportsPage.vue' => 'События не найдены',
        'pages/identity/DigitalPassesPage.vue' => 'Цифровые пропуска не найдены',
        'pages/identity/RfidCardsPage.vue' => ['Карт нет', 'Записей нет'],

        // Двух экранов области здесь намеренно нет, и это сказано вслух, чтобы
        // следующий не счёл их забытыми.
        //
        // У «Точек прохода» пустого состояния нет вовсе: числа стоят строкой в
        // панели — «Корпусов: 0 · точек прохода: 0» при трёх и трёх. Починены
        // они тем же `referenceLoaded`, но этот сторож смотрит `AppEmptyState`
        // и увидеть их не может; держит их только обход с обрывом запроса.
        //
        // Общежитие честно **формулировкой**, а не ветвлением: «Сводка не
        // загрузилась» верна и когда данных нет, и когда спросить не удалось,
        // поэтому спрашивать ему нечего — сторож объявил бы виноватым исправный
        // экран. Слабое место у такой честности своё: перепишут подпись на
        // «Записей нет» — и ничто здесь этого не заметит.
    ];

    /**
     * Чем экран отличает отказ — признаков два, и они не одно и то же.
     *
     * `store.error` годится там, где у хранилища один источник ошибок. Где их
     * несколько, он подводит: на экране нагрузки ошибку поднимают ещё импорт,
     * экспорт и сохранение, и после неудачного экспорта список цел, а признак
     * уже поднят — экран сказал бы «не получено» о том, что получено.
     * `loaded` отвечает ровно на нужный вопрос: пришёл ли **этот** список.
     *
     * Поэтому принимается любой из двух. Навязывать один — это и есть тот
     * сторож, который вынуждает переписывать работающие экраны под себя;
     * ровно об этом сказано выше про две формы записи.
     */
    private const REFUSAL_ASKED = ['store.error', 'store.loaded', 'store.referencesLoaded'];

    /**
     * Имя признака «дошёл ли ответ» у каждого хранилища своё.
     *
     * За один вечер 04.09.2026 в одной только области проходной их набралось
     * четыре: `musterLoaded`, `referenceLoaded`, `cardsLoaded`, `journalLoaded`
     * — по признаку на список, потому что на экране карт списка два и пришёл
     * один. Список литералов выше такой рост догоняет строкой на каждый новый
     * (и однажды не догонит молча), поэтому рядом стоит шаблон: он принимает
     * любое `store.…Loaded`, не требуя вписывать имя.
     */
    private const REFUSAL_PATTERN = '~store\\.[A-Za-z]*[Ll]oaded\\b~';

    public function test_the_empty_list_asks_whether_the_request_failed(): void
    {
        $mute = [];
        $missing = [];
        $read = 0;

        foreach (self::SCREENS as $path => $lies) {
            $source = $this->frontendFile($path);

            if ($source === null) {
                $missing[] = $path;
                continue;
            }

            $read++;

            foreach ((array) $lies as $lie) {
                $groups = array_values(array_filter(
                    $this->emptyStateGroups($source),
                    fn (string $group): bool => str_contains($group, $lie),
                ));

                if ($groups === []) {
                    $mute[] = $path.': не нашлось пустого состояния списка (подпись «'.$lie.'» переписали — проверьте, что вместе с ней не потеряли отличие отказа)';
                    continue;
                }

                foreach ($groups as $group) {
                    if (! $this->refusalAsked($group)) {
                        $mute[] = $path.': «'.$lie.'» говорится, не спросив, не отказал ли запрос';
                    }
                }
            }
        }

        // Ни одного файла — фронтенда рядом нет, это прогон по `backend/`.
        // **Часть файлов — другое дело:** экран переименовали или унесли, и молчать
        // тут нельзя. Строка списка прикрывала бы уже несуществующее, а проверка
        // выглядела бы работающей — ровно так список внешних ключей у `groups`
        // разошёлся со схемой, оставаясь зелёным.
        if ($read === 0) {
            $this->markTestSkipped('Рядом нет каталога frontend: проверка идёт в полном дереве, как в CI.');
        }

        $this->assertSame([], $missing,
            "экран из списка не найден — переименован или унесён, впишите новый путь:\n".implode("\n", $missing));

        $this->assertSame([], $mute, "пустое состояние выдаёт отказ за пустоту:\n".implode("\n", $mute));
    }

    /** Спрошено ли в группе, дошёл ли ответ и не отказал ли запрос. */
    private function refusalAsked(string $group): bool
    {
        foreach (self::REFUSAL_ASKED as $sign) {
            if (str_contains($group, $sign)) {
                return true;
            }
        }

        return preg_match(self::REFUSAL_PATTERN, $group) === 1;
    }

    /**
     * Соседние `AppEmptyState` — одной группой.
     *
     * Соседними считаем те, между которыми нет ничего, кроме пробелов: это и
     * есть развилка «нет данных / не спросили», записанная двумя тегами. Тег,
     * стоящий отдельно (например, «Пользователь не выбран» в правой колонке),
     * остаётся своей группой и чужой отказ на себя не примеряет.
     *
     * @return list<string>
     */
    private function emptyStateGroups(string $source): array
    {
        preg_match_all('~<AppEmptyState\b[^>]*?/?>~su', $source, $tags, PREG_OFFSET_CAPTURE);

        $groups = [];
        $current = '';
        $endOfPrevious = null;

        foreach ($tags[0] as [$tag, $offset]) {
            $between = $endOfPrevious === null ? null : substr($source, $endOfPrevious, $offset - $endOfPrevious);

            if ($between !== null && trim($between) === '') {
                $current .= $tag;
            } else {
                if ($current !== '') {
                    $groups[] = $current;
                }
                $current = $tag;
            }

            $endOfPrevious = $offset + strlen($tag);
        }

        if ($current !== '') {
            $groups[] = $current;
        }

        return $groups;
    }

    private function frontendFile(string $path): ?string
    {
        $full = base_path('../frontend/src/'.$path);

        return is_readable($full) ? (string) file_get_contents($full) : null;
    }
}
