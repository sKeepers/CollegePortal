#!/bin/sh
#
# Сколько запросов портал обслуживает одновременно.
#
# Образ `php:fpm` по умолчанию даёт **пять** рабочих процессов, и это умолчание,
# которого никто не писал: его не видно ни в коде приложения, ни в настройках
# развёртывания, и ищут его последним. Замер 01.09.2026 на стенде (16 ядер):
#
#   нагрузка 50 одновременных сеансов, пять процессов
#     процессор упёрся в 467 % при 1600 % доступных — ровно потолок пяти
#     p95 ответа 5 727 мс, то есть портал стоял на трети машины
#
#   те же 50 при двадцати четырёх процессах
#     p95 1 719 мс; стена отодвинулась с 50 одновременных к 200
#
# Разбор целиком, с кривой на 10-200 — `docs/LOAD_PROBE_2026-09-01.md`.
#
# **Число задаётся настройкой, а не вбито**: на машине с другим числом ядер его
# меняют строкой в окружении, а не пересборкой образа. Умолчание рассчитано на
# шестнадцать ядер — столько на стенде и на боевом сервере (замер координатора,
# 01.09.2026).
#
# Память: рабочий процесс держит 48-58 МБ (замер там же), потолок одного —
# `memory_limit` 128 МБ. Двадцать четыре процесса это около 1,4 ГБ по факту и
# 3 ГБ в худшем случае; на боевом 15 ГБ.
set -e

# `--write-only`: записать настройку и выйти, не запуская php-fpm.
#
# Релизный образ работает от `www-data`, а каталог пулов принадлежит root: на
# запуске файл там создать уже нельзя, и настройка молча осталась бы
# умолчанием образа. Поэтому в релизном образе этот же скрипт зовётся **на
# сборке**, root'ом, с этим ключом. Число живёт в одном месте на оба образа.
WRITE_ONLY=""
if [ "$1" = "--write-only" ]; then
    WRITE_ONLY="да"
    shift
fi

CHILDREN="${PHP_FPM_MAX_CHILDREN:-24}"
START="${PHP_FPM_START_SERVERS:-8}"
MIN_SPARE="${PHP_FPM_MIN_SPARE_SERVERS:-4}"
MAX_SPARE="${PHP_FPM_MAX_SPARE_SERVERS:-16}"

# Отдельным файлом, а не правкой `www.conf`: так видно, что число наше, а не
# осталось от образа, и так его не затрёт обновление базового образа.
#
# Не получилось записать — идём дальше, а не падаем. Этим же образом гоняются
# тесты (`docker run ... php artisan test`), и уронить прогон из-за настройки,
# которая тестам не нужна вовсе, было бы хуже самой настройки.
POOL_DIR=/usr/local/etc/php-fpm.d

if [ -w "$POOL_DIR" ]; then
    cat > "$POOL_DIR/zz-portal.conf" <<CONF
[www]
pm = dynamic
pm.max_children = ${CHILDREN}
pm.start_servers = ${START}
pm.min_spare_servers = ${MIN_SPARE}
pm.max_spare_servers = ${MAX_SPARE}
CONF
elif [ -n "$WRITE_ONLY" ]; then
    # На сборке это отказ, а не мелочь: образ уехал бы с пятью процессами из
    # умолчания `php:fpm`, и узнали бы об этом на боевом, на пункте Б4 приёмки.
    echo "portal-entrypoint: ${POOL_DIR} недоступен на запись при сборке образа" >&2
    exit 1
else
    echo "portal-entrypoint: ${POOL_DIR} недоступен на запись, число рабочих процессов остаётся от образа" >&2
fi

if [ -n "$WRITE_ONLY" ]; then
    exit 0
fi

exec docker-php-entrypoint "$@"
