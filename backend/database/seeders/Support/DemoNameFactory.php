    /** @var array<string, true> */
    private array $used = [];

    public function __construct(int $seed = 20260810)
    {
        mt_srand($seed);
    }

    /**
     * @return array{last_name:string, first_name:string, middle_name:string, gender:string}
     */
    public function next(?string $gender = null): array
    {
        $gender ??= mt_rand(0, 1) === 1 ? 'female' : 'male';

        // Двадцать попыток, а дальше берём как есть: полные тёзки в наборе на
        // шестьсот человек и должны иногда встречаться, но не косяками.
        for ($attempt = 0; $attempt < 20; $attempt++) {
            $name = $this->compose($gender);
            $key = mb_strtolower("{$name['last_name']} {$name['first_name']} {$name['middle_name']}");

            if (! isset($this->used[$key])) {
                $this->used[$key] = true;

                return $name;
            }
        }

        return $this->compose($gender);
    }

    /**
     * @return array{last_name:string, first_name:string, middle_name:string, gender:string}
     */
    private function compose(string $gender): array
    {
        $female = $gender === 'female';
        $surname = self::SURNAMES[$this->weightedIndex(count(self::SURNAMES))];
        $names = $female ? self::FEMALE_NAMES : self::MALE_NAMES;
        $patronymic = self::PATRONYMICS[mt_rand(0, count(self::PATRONYMICS) - 1)];

        return [
            'last_name' => $female ? $this->toFemaleSurname($surname) : $surname,
            'first_name' => $names[$this->weightedIndex(count($names))],
            'middle_name' => $patronymic[$female ? 1 : 0],
            'gender' => $gender,
        ];
    }

    /**
     * Смещение к началу списка: в жизни распределение фамилий не равномерное,
     * Ивановых заметно больше, чем Одинцовых, и набор с одинаковой частотой
     * всех фамилий читается так же неестественно, как набор из одной.
     */
    private function weightedIndex(int $count): int
    {
        $uniform = mt_rand(0, mt_getrandmax()) / mt_getrandmax();

        return min($count - 1, (int) floor($uniform ** 1.7 * $count));
    }

    /**
     * Женская форма фамилии. Несклоняемые — на -ко, -ук, -ых, -их — остаются
     * как есть, иначе в списке появляются «Шевченкова» и «Седыхова».
     */
    private function toFemaleSurname(string $surname): string
    {
        $endings = [
            'ский' => 'ская',
            'цкий' => 'цкая',
            'ой' => 'ая',
            'ёв' => 'ёва',
            'ев' => 'ева',
            'ов' => 'ова',
            'ин' => 'ина',
            'ын' => 'ына',
        ];

        foreach ($endings as $male => $female) {
            if (mb_substr($surname, -mb_strlen($male)) === $male) {
                return mb_substr($surname, 0, -mb_strlen($male)).$female;
            }
        }

        return $surname;
    }
