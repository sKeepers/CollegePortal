#!/usr/bin/env bash
# Срабатывает перед сжатием контекста (PreCompact).
#
# Делает две вещи. Первая — механическая: складывает копию всего
# незакоммиченного в .local/snapshots/<дата_время>/. Это страховка от того,
# что случалось трижды за август: работа существовала в одном экземпляре в
# локальной копии, и чужой `git checkout` стирал её без следа.
#
# Вторая — говорит чату, что успеть до сжатия: закоммитить, дописать доску,
# не начинать новое. Длинную инструкцию в этот момент давать нельзя, она
# съедает остаток контекста — поэтому три пункта, а не девять.
#
# Снимок не заменяет коммит: .local вне git, и на DEV он не уезжает.
set -u

root="${CLAUDE_PROJECT_DIR:-$(pwd)}"
cd "$root" 2>/dev/null || exit 0
command -v git >/dev/null 2>&1 || exit 0
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || exit 0

dest=".local/snapshots/$(date +%Y-%m-%d_%H%M%S)"
saved=0

# core.quotePath=false — иначе кириллические имена приезжают как \320\237...
while IFS= read -r f; do
  [ -n "$f" ] || continue
  [ -f "$f" ] || continue
  mkdir -p "$dest/$(dirname "$f")" 2>/dev/null || continue
  cp -p "$f" "$dest/$f" 2>/dev/null && saved=$((saved + 1))
done < <(git -c core.quotePath=false status --porcelain 2>/dev/null | cut -c4-)

if [ "$saved" -gt 0 ]; then
  note="Контекст сжимается. Незакоммиченных файлов: $saved, копия сложена в $dest — это страховка, а не сохранение работы."
else
  note="Контекст сжимается. Незакоммиченного в рабочей копии нет."
fi

ctx="Контекст сейчас будет сжат. Прежде чем это произойдёт, останови работу и сохрани состояние — коротко, тремя пунктами: 1) закоммить всё незакоммиченное, хоть черновиком, и назови ветку; 2) допиши на доску docs/ACTIVE_WORK.md — ветка, что сделано, на чём именно остановился (файл и место), следующий шаг одной строкой; 3) новое не начинай. После сжатия первым делом перечитай CLAUDE.md, свой раздел в docs/prompts/ASSIGNMENTS.md и свою запись на доске: пересказ теряет имена файлов и причины решений, а эти три источника их хранят."

printf '{"systemMessage":"%s","hookSpecificOutput":{"hookEventName":"PreCompact","additionalContext":"%s"}}' "$note" "$ctx"
