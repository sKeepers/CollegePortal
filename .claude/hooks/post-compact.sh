#!/usr/bin/env bash
# Срабатывает после сжатия контекста (PostCompact).
#
# Сжатие оставляет пересказ. Первыми из пересказа выпадают имена файлов,
# номера строк и причины, по которым сделано именно так, — то есть ровно то,
# без чего чат начинает переспрашивать уже решённое или лезть в чужую область.
#
# Поэтому сразу после сжатия возвращаем чат к трём источникам, которые всё это
# хранят, и отдельно предупреждаем про недописанную правку: дописывать её по
# памяти — верный способ смешать два замысла в одном файле.
set -u

printf '{"hookSpecificOutput":{"hookEventName":"PostCompact","additionalContext":"%s"}}' "Контекст был сжат, и всё, чего нет в репозитории, ты помнишь только пересказом. Прежде чем продолжать: перечитай CLAUDE.md, свой раздел в docs/prompts/ASSIGNMENTS.md и свою запись на доске docs/ACTIVE_WORK.md. Если правка осталась недописанной — посмотри git status и git diff и продолжай от того, что там, а не по памяти: дописанное по памяти смешивает два замысла в одном файле. Чужие области не трогай, даже если кажется, что там мелочь."
