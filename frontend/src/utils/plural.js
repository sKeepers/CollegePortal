/**
 * Согласование существительного с числом по-русски.
 *
 * Форма зависит от последней цифры и от предпоследней: 1 место, 2 места,
 * 5 мест, 21 место, 22 места, но 11 мест и 12 мест — исключение на второй
 * десяток, которое ломает наивное правило «смотрим последнюю цифру».
 *
 * Заведено 24.08.2026, когда печатный список проживающих впервые посмотрели
 * глазами: в шапке стояло «Занято 2 из 51 мест», а в каждой свободной комнате
 * «свободна (3 мест)». На экране этого не было — только на бумаге, которую
 * вешают на дверь. Такие строки в портале будут ещё, поэтому функция общая, а
 * не две правки по месту.
 *
 * @param {number} count сколько
 * @param {[string, string, string]} forms [для 1, для 2-4, для 5-20]
 * @returns {string} только слово, без числа: число подставляет вызывающий, и
 *   иногда оно пишется отдельно от слова («2 из 51 места»)
 */
export function pluralForm(count, forms) {
  const n = Math.abs(Number(count))

  if (!Number.isFinite(n)) {
    return forms[2]
  }

  const tail = Math.floor(n) % 100

  // Второй десяток целиком берёт форму множественного числа: 11, 12, 13, 14 —
  // «мест», хотя последняя цифра говорит об обратном.
  if (tail >= 11 && tail <= 14) {
    return forms[2]
  }

  const last = tail % 10

  if (last === 1) {
    return forms[0]
  }

  if (last >= 2 && last <= 4) {
    return forms[1]
  }

  return forms[2]
}

/** Число вместе со словом: «3 места». */
export function plural(count, forms) {
  return `${count} ${pluralForm(count, forms)}`
}

