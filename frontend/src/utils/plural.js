/**
 * Тот же счёт мест, но в родительном падеже — после предлога «из».
 *
 * «Занято 2 из 51 место» — так лист печатался до 28.08.2026, и это не
 * опечатка в слове, а неверный падеж: `PLACES` даёт именительный («51
 * место»), а после «из» нужен родительный («из 51 места»). Разница видна
 * только на числах, оканчивающихся на 1: у остальных обе формы совпадают
 * («из 2 мест», «из 5 мест»), поэтому ошибка и простояла — на 51 месте
 * стенда она есть, на 50 её бы не было.
 */
