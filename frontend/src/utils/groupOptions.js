/**
 * Список групп для выпадающих полей: заголовок специальности и строки курсов под ним.
 *
 * Групп в колледже под семьдесят, и плоским списком они нечитаемы: подряд идут четыре
 * «Хореографическое творчество», различающиеся только годом набора в конце строки.
 * Владелец 23.08.2026 попросил показывать «только название», но буквально это невозможно —
 * четыре строки стали бы неотличимы. Решение: группировать по специальности, а строкой
 * писать курс, которым учебная часть оперирует каждый день.
 *
 * **Одна поправка к решению, и она вынужденная.** В решении сказано «а где есть параллели —
 * „1 курс А“, „1 курс Б“». Буквенных параллелей больше нет, и это тоже решение владельца:
 * буква в имени означала не параллель, а источник оплаты («Группа А (бюджетная)»), 24.08.2026
 * оплата уехала в карточку студента, десять пар групп слились в одну и буквы сняли. Платники
 * и бюджетники учатся вместе; подгруппы, когда дойдут до портала, станут отдельной сущностью,
 * а не буквой в имени.
 *
 * Различаются же группы внутри специальности **специализацией**: под «51.02.01 Народное
 * художественное творчество» лежат и «Театральное творчество», и «Хореографическое
 * творчество». Напиши обеим «4 курс» — и получишь две неотличимые строки, то есть ровно ту
 * беду, от которой уходили. Поэтому специализация приписывается к курсу.
 *
 * **Приписывается всегда, без исключений.** Сначала её писали только там, где
 * специализаций в специальности больше одной: под «53.02.04 Вокальное искусство» она одна,
 * и приписывать нечего. Владелец посмотрел живьём и сказал: **«пустой список у
 * „Вокальное искусство“ и некоторых других»**. Список не был пуст — под заголовком стояли
 * «1 курс», «2 курс», «3 курс», «4 курс», — но **строка без названия читается как
 * пустая**, и рядом со строками вида «4 курс — Инструменты народного оркестра» это
 * выглядит перечнем без имён.
 *
 * Повтор названия под собственным заголовком владельца не смущает — он сказал это дважды
 * разными словами, второй раз: «пусть пишется полностью, как у всех». Голая строка
 * смущает. Единообразие здесь дороже краткости: одно правило на все строки.
 *
 * Специализация берётся из имени группы отсечением хвоста «, набор 2026»: на 24.08.2026 им
 * кончаются **все** 58 групп стенда, исключений нет. Имя группы в базе при этом не меняется —
 * оно уходит в приказы, отчёты и ФИС; меняется только вид списка.
 */

/** Хвост «, набор 2026» — им кончается имя каждой группы. */
const ENROLMENT_TAIL = /,\s*набор\s+\d{4}\s*$/u

const NO_SPECIALTY = 'Без специальности'

/** Имя группы без года набора — то, чем специализации различаются между собой. */
export function groupKind(group) {
  const name = String(group?.name ?? '').trim()

  return name.replace(ENROLMENT_TAIL, '').trim() || name
}

function specialtyOf(group) {
  return String(group?.specialty ?? '').trim() || NO_SPECIALTY
}

function courseOf(group) {
  const course = Number(group?.course)

  return Number.isFinite(course) && course > 0 ? course : null
}

/**
 * Строка группы: «2 курс — Театральное творчество».
 *
 * Курса может не быть — у заочников и у групп, чей год набора не заполнен. Тогда пишем год
 * набора: он есть всегда и человеку понятнее пустоты.
 */
function rowLabel(group) {
  const course = courseOf(group)
  const head = course ? `${course} курс` : `набор ${group?.year_start ?? '—'}`

  return `${head} — ${groupKind(group)}`
}

function compare(a, b) {
  const bySpecialty = specialtyOf(a).localeCompare(specialtyOf(b), 'ru')
  if (bySpecialty !== 0) return bySpecialty

  // Группы без курса — в конец: это заочники и незаполненные, им не место между курсами.
  const courseA = courseOf(a) ?? Number.MAX_SAFE_INTEGER
  const courseB = courseOf(b) ?? Number.MAX_SAFE_INTEGER
  if (courseA !== courseB) return courseA - courseB

  return groupKind(a).localeCompare(groupKind(b), 'ru')
}

/**
 * @param {Array} groups список групп как их отдаёт API
 * @param {object} [options]
 * @param {(group: object) => (string|null|undefined)} [options.suffix] что дописать к строке через « · »
 * @param {(group: object) => object} [options.extra] дополнительные поля варианта
 * @param {Array} [options.lead] что поставить в самое начало, например «Все группы»
 * @returns {Array} варианты для `q-select`; заголовки помечены `disable`, выбрать их нельзя,
 * а у строк рядом с коротким `label` лежит полное имя группы в `fullLabel`
 */
/**
 * Найти вариант группы по значению фильтра.
 *
 * Три конца, и каждый закрывает свой путь, которым шапка печатной ведомости уже
 * ошибалась или могла ошибиться. Звать `find` напрямую по `option.value` больше не надо
 * нигде: три раза за день это кончалось неправдой на бумаге.
 *
 * **Пустое не ищется вовсе.** `null`, `undefined` и пустая строка значат «отбора нет», а
 * не «найди что-нибудь». Пока `find` звали напрямую, пустой фильтр находил первый
 * заголовок списка, и его название уезжало в шапку подписываемого документа.
 *
 * **Заголовки отсеиваются явно** по `isSpecialtyHeader`, а не потому, что их значение
 * «не похоже» на идентификатор. Непохожесть — свойство, которое теряется при следующей
 * правке молча; намерение держится.
 *
 * **Сравнение числовое.** Из `q-select` идентификатор приходит числом, из адресной
 * строки пришёл бы строкой, а `'32' === 32` — ложь: настоящая группа не нашлась бы, и
 * лист вышел бы под общим заголовком вместо имени группы. На экране карт такого пути
 * сегодня нет — проверено, фильтр там живёт только в `q-select`, — но заводится он одной
 * строкой `route.query`, и тогда ошибка вернётся молча.
 */
export function findGroupOption(options, value) {
  if (value === null || value === undefined || value === '') return undefined

  const wanted = Number(value)

  if (Number.isNaN(wanted)) return undefined

  return (Array.isArray(options) ? options : []).find(
    (option) => !option.isSpecialtyHeader && Number(option.value) === wanted,
  )
}

export function buildGroupOptions(groups, { suffix = null, extra = null, lead = [] } = {}) {
  const rows = (Array.isArray(groups) ? groups : []).filter(Boolean)

  const options = [...lead]
  let currentSpecialty = null

  ;[...rows].sort(compare).forEach((group) => {
    const specialty = specialtyOf(group)

    if (specialty !== currentSpecialty) {
      currentSpecialty = specialty
      // Заголовок — тоже вариант списка, но невыбираемый. Значение у него **строковое и
      // заведомо непохожее на идентификатор группы**, и это не украшение.
      //
      // Стоял `value: null` с пояснением «`find` по значению его не найдёт». Пояснение
      // было неверным, и цена ошибки — печатная ведомость выдачи карт: её шапка ищет
      // группу как `find((o) => o.value === filters.group_id)`, а без выбранной группы
      // `group_id` равен `null`. `null === null` — истина, находился **первый заголовок**,
      // и его название уезжало в шапку вместо «Журнал выдачи RFID-карт».
      //
      // Поправка 24.08.2026, по замеру: на листе владельца стояло «Ведомость выдачи
      // RFID-карт — Без специальности», и ничего другого там стоять не могло. Ручка
      // `rfid-cards/groups` не отдавала поле `specialty` вовсе, поэтому заголовок в том
      // списке был **единственным** и назывался «Без специальности» — а группировки по
      // специальности на том экране не происходило ни дня. Прежняя редакция называла
      // здесь код специальности и была помечена проверенной; проверена она не была.
      //
      // Строка `specialty:<название>` не равна ни `null`, ни пустой строке, ни числу — и
      // не станет равной ни при `===`, ни при `String()`, ни при `Number()` (там `NaN`).
      // Поэтому чинится здесь, а не в каждом месте, которое ищет группу по значению.
      options.push({
        label: specialty,
        value: `specialty:${specialty}`,
        disable: true,
        isSpecialtyHeader: true,
      })
    }

    const tail = suffix ? suffix(group) : null

    options.push({
      label: [rowLabel(group), tail].filter(Boolean).join(' · '),
      // Полное имя обязано остаться рядом: в списке под заголовком специальности хватает
      // «2 курс», а в фишке фильтра и в шапке печатной ведомости — нет, там заголовка нет
      // и «2 курс» не говорит ни о чём. Кто показывает группу вне списка, берёт `fullLabel`.
      fullLabel: group.name,
      value: group.id,
      group,
      ...(extra ? extra(group) : {}),
    })
  })

  return options
}
