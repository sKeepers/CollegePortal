/**
 * Даты без времени на печатных документах.
 *
 * Заведено 28.08.2026, когда отчёт заселённости впервые увидели глазами: в
 * подзаголовке стояло «За период 2026-07-29 — 2026-08-28», а в подвале того же
 * листа «Составлен 28.08.2026». Два вида дат на одной странице — читатель
 * решает, что это разные вещи, хотя это одна и та же вещь.
 *
 * **Через `new Date()` такую дату форматировать нельзя.** Строка вида
 * `2026-07-29` разбирается как полночь UTC, и у читателя западнее Гринвича
 * `toLocaleDateString` покажет **28 июля** — день уедет назад на печатном
 * документе. Здесь у значения времени нет вовсе, поэтому и разбирать его как
 * момент незачем: перестановка трёх кусков строки однозначна и не зависит ни
 * от часов машины, ни от пояса.
 *
 * Замерено: `new Date('2026-07-29').toLocaleDateString('ru-RU')` в поясе
 * `America/New_York` даёт `28.07.2026`.
 *
 * @param {string} value календарная дата `ГГГГ-ММ-ДД`
 * @returns {string} `ДД.ММ.ГГГГ`, а при непонятном значении — оно само
 */
export function formatDay(value) {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(value ?? '').trim())

  return match ? `${match[3]}.${match[2]}.${match[1]}` : String(value ?? '')
}
