/**
 * Единое написание телефона для показа: +7 962 448 7133.
 *
 * В базе номера лежат как придётся: заведённые вручную — без плюса
 * (`79624487133`), выданные автоматически — с плюсом, импортированные —
 * со скобками и дефисами. На экране это выглядело тремя разными полями
 * одного и того же вида, а глазами номера не сравнивались.
 *
 * Хранение это не меняет: форматирование только на выводе.
 */
export function formatPhone(value, fallback = '') {
  const raw = String(value ?? '').trim()

  if (raw === '') {
    return fallback
  }

  const digits = raw.replace(/\D+/g, '')
  const russian = digits.match(/^(?:7|8)(\d{3})(\d{3})(\d{2})(\d{2})$/) || digits.match(/^(\d{3})(\d{3})(\d{2})(\d{2})$/)

  if (! russian) {
    // Чужой формат не ломаем: короткий внутренний, международный или заведомо
    // неполный номер показываем как есть, иначе правка вслепую исказит данные.
    return raw
  }

  const [, code, first, second, third] = russian

  return `+7 ${code} ${first} ${second}${third}`
}
